List<Perfume> _validateAdditionalCatalogSeed(List<Perfume> products) {
  if (products.length != 40) {
    throw StateError(
      'The additional catalog seed must contain exactly 40 products.',
    );
  }

  final ids = <String>{};
  final productKeys = <String>{};
  for (final product in products) {
    if (!ids.add(product.id)) {
      throw StateError('Duplicate catalog product ID: ${product.id}.');
    }

    final productKey =
        '${product.brandId.trim().toLowerCase()}::'
        '${product.name.trim().toLowerCase()}';
    if (!productKeys.add(productKey)) {
      throw StateError(
        'Duplicate catalog product: ${product.brandName} ${product.name}.',
      );
    }
  }

  return List.unmodifiable(products);
}

Perfume _seedPerfume({
  required String id,
  required String brandId,
  required String brandName,
  required String name,
  required GenderPreference gender,
  required FragranceFamily family,
  required Concentration concentration,
  required int priceCentavos,
}) {
  final notes = switch (family) {
    FragranceFamily.citrus => (
      ['Bergamot', 'Lemon'],
      ['Neroli', 'Orange blossom'],
      ['Musk', 'Amber'],
    ),
    FragranceFamily.floral => (
      ['Pear', 'Bergamot'],
      ['Rose', 'Jasmine'],
      ['Musk', 'Vanilla'],
    ),
    FragranceFamily.woody => (
      ['Pepper', 'Cardamom'],
      ['Cedar', 'Sandalwood'],
      ['Vetiver', 'Amber'],
    ),
    FragranceFamily.oriental => (
      ['Pink pepper', 'Cinnamon'],
      ['Coffee', 'Jasmine'],
      ['Vanilla', 'Patchouli'],
    ),
    FragranceFamily.fresh => (
      ['Citrus', 'Green notes'],
      ['Sea salt', 'Lavender'],
      ['Musk', 'Driftwood'],
    ),
    FragranceFamily.gourmand => (
      ['Caramel', 'Citrus'],
      ['Cocoa', 'Coffee'],
      ['Vanilla', 'Tonka bean'],
    ),
    FragranceFamily.chypre => (
      ['Bergamot', 'Pepper'],
      ['Rose', 'Patchouli'],
      ['Moss', 'Musk'],
    ),
    FragranceFamily.aquatic => (
      ['Marine notes', 'Bergamot'],
      ['Rosemary', 'Geranium'],
      ['Musk', 'Patchouli'],
    ),
    FragranceFamily.leather => (
      ['Saffron', 'Cardamom'],
      ['Leather', 'Iris'],
      ['Amber', 'Wood'],
    ),
    FragranceFamily.aromatic => (
      ['Apple', 'Bergamot'],
      ['Lavender', 'Geranium'],
      ['Cedar', 'Tonka bean'],
    ),
  };

  final occasions = switch (family) {
    FragranceFamily.citrus ||
    FragranceFamily.fresh => [Occasion.everyday, Occasion.travel],
    FragranceFamily.floral ||
    FragranceFamily.gourmand => [Occasion.dateNight, Occasion.special],
    FragranceFamily.woody ||
    FragranceFamily.leather => [Occasion.office, Occasion.evening],
    _ => [Occasion.everyday, Occasion.evening],
  };

  final vibes = switch (family) {
    FragranceFamily.citrus ||
    FragranceFamily.aquatic => [ScentVibe.clean, ScentVibe.energetic],
    FragranceFamily.floral => [ScentVibe.elegant, ScentVibe.romantic],
    FragranceFamily.woody ||
    FragranceFamily.leather => [ScentVibe.bold, ScentVibe.mysterious],
    FragranceFamily.fresh => [ScentVibe.clean, ScentVibe.calming],
    FragranceFamily.oriental ||
    FragranceFamily.gourmand => [ScentVibe.romantic, ScentVibe.bold],
    FragranceFamily.chypre => [ScentVibe.elegant, ScentVibe.mysterious],
    FragranceFamily.aromatic => [ScentVibe.clean, ScentVibe.elegant],
  };

  return Perfume(
    id: id,
    brandId: brandId,
    brandName: brandName,
    name: name,
    description: 'A curated ${family.name} fragrance from $brandName.',
    gender: gender,
    family: family,
    concentration: concentration,
    occasions: occasions,
    vibes: vibes,
    topNotes: notes.$1,
    heartNotes: notes.$2,
    baseNotes: notes.$3,
    variants: [
      PerfumeVariant(
        id: '$id-50',
        label: '50ml',
        volumeMl: 50,
        price: Money(priceCentavos),
        stock: 12,
      ),
      PerfumeVariant(
        id: '$id-100',
        label: '100ml',
        volumeMl: 100,
        price: Money(priceCentavos + 200_000),
        stock: 6,
      ),
    ],
    tags: [family.name, gender.wireValue, brandName.toLowerCase()],
  );
}
